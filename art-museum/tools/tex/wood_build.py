def src(stem):
    files = sorted(glob.glob(os.path.join(RAW, stem + '-*.png')))
    assert files, 'missing raw image ' + stem
    return Image.open(files[-1]).convert('RGB')


def recolor(a, rgb):
    """Per-channel gain so the mean colour of float image `a` becomes `rgb` (0..255)."""
    return a * (np.array(rgb, np.float32) / 255.0 / a.reshape(-1, 3).mean(0))


def desat(a, k):
    lum = a.mean(2, keepdims=True)
    return lum + (a - lum) * (1 - k)


def sample(a, x, y, mode='nearest'):
    """Bilinear lookup of float image a[h,w,3] at pixel coords x, y (arrays of equal shape)."""
    return np.dstack([ndimage.map_coordinates(a[..., c], [y, x], order=1, mode=mode) for c in range(3)])


def tileable(im, band=0.14, seed=1, sig=6.0, axes=(0, 1)):
    """Like textools.make_tileable, but the cross-fade keeps local contrast (fine grain is not washed out in the blend band)."""
    a = T.to_f(im); rng = np.random.default_rng(seed)
    for axis in axes:
        a = np.moveaxis(a, axis, 0)
        n = a.shape[0]; b = int(n * band)
        w = np.linspace(0, 1, b, dtype=np.float32)[:, None]
        noise = ndimage.gaussian_filter(rng.standard_normal((b, a.shape[1])).astype(np.float32), 6); noise /= (np.abs(noise).max() + 1e-6)
        m = np.clip((w + noise * 0.35 * (1 - np.abs(2 * w - 1)) - 0.5) * 3.0 + 0.5, 0, 1)[..., None]
        low = ndimage.gaussian_filter(a, (sig, sig, 0), mode='reflect')
        head, tail, lh, lt = a[:b], a[n - b:], low[:b], low[n - b:]
        mix = m * lh + (1 - m) * lt + (m * (head - lh) + (1 - m) * (tail - lt)) / np.sqrt(m * m + (1 - m) * (1 - m))
        a = np.moveaxis(np.concatenate([mix, a[b:n - b]], 0), 0, axis)
    return T.to_im(a)


def resize_wrap(im, size):
    """LANCZOS resize of a periodic image that stays exactly periodic (resize a 3x3 tiling, keep the centre)."""
    w, h = size
    return T.tile_preview(im, 3, 3, max_side=10 ** 9).resize((3 * w, 3 * h), Image.LANCZOS).crop((w, h, 2 * w, 2 * h))


def seam(im):
    a = np.asarray(im.convert('RGB'), np.float32)
    return 'wrap/neighbour diff rows %.2f/%.2f cols %.2f/%.2f' % (
        np.abs(a[0] - a[-1]).mean(), np.abs(np.diff(a, axis=0)).mean(), np.abs(a[:, 0] - a[:, -1]).mean(), np.abs(np.diff(a, axis=1)).mean())


def exact_mean(im, target):
    for _ in range(3):  # clipping/rounding can move the mean a little: iterate
        im = T.set_mean(im, target * target / (np.asarray(im, np.float32).mean() or 1) if _ else target)
    return im


def finish(im, name, q=88):
    path = os.path.join(OUT, name + '.webp')
    print('   before webp: ' + seam(im))
    T.save_webp(im, path, q=q)
    back = Image.open(path).convert('RGB')
    T.tile_preview(back).save(os.path.join(RAW, 'preview_%s.png' % name))
    m = float(np.asarray(back, np.float32).mean())
    print('%-14s %s mean sRGB %.1f  linear %s' % (name, back.size, m, T.mean_linear(back)))
    return back


# ------------------------------------------------------------------ parquet
def parquet():
    W, n = 0.1, 6                       # plank width (m), length = n * W
    TU, TV = 17 * W * np.sqrt(2), 3 * n * W * np.sqrt(2)   # 2.404 x 2.546 m, exact lattice periods
    N, SS = 1024, 3
    M = N * SS
    rng = np.random.default_rng(7)

    # two oak sources, both graded to the same honey oak colour; grain horizontal
    honey = (187, 152, 109)
    A = recolor(T.to_f(T.flatten(src('src_oak_parquet'), 0.18)), honey)
    B = recolor(T.to_f(T.flatten(src('src_oak_veneer'), 0.18)), honey)
    B = B.mean() + (B - B.mean((0, 1))) * 1.25 + (B.mean((0, 1)) - B.mean())   # veneer is flatter: a little more grain contrast
    S = np.concatenate([A, B], 0)       # atlas: A on top (rows 0..1023), B below (rows 1024..2047)
    sh, sw = A.shape[:2]
    ppm = 1150.0                        # source pixels per metre (plank = 690 x 115 px of source)
    cw, ch = int(n * W * ppm) + 2, int(W * ppm) + 2

    def lattice(m):
        """tile pixel grid (m x m) -> plank id, position along (0..n) and across (0..1) the plank, row key, index in row"""
        u = (np.arange(m, dtype=np.float64) + 0.5) / m * TU
        v = (np.arange(m, dtype=np.float64) + 0.5) / m * TV
        u, v = np.meshgrid(u, v)
        x = (u + v) / np.sqrt(2) / W                        # unrotated herringbone coordinates in plank widths
        y = (u - v) / np.sqrt(2) / W
        i, j = np.floor(x).astype(np.int64), np.floor(y).astype(np.int64)
        fx, fy = x - i, y - j
        d = np.mod(i - j, 2 * n)
        isH = d < n
        s = np.where(isH, d + fx, (2 * n - 1 - d) + fy)
        t = np.where(isH, fy, fx)
        i0 = np.where(isH, i - d, i)                        # plank origin cell
        j0 = np.where(isH, j, j - (2 * n - 1 - d))
        # the tile is 34 x 36 in units of W/sqrt(2); (i0+j0, i0-j0) is periodic in exactly those units
        ka, kb = np.mod(i0 + j0, 34), np.mod(i0 - j0, 36)
        return isH.astype(np.int64) * (34 * 36) + ka * 36 + kb, s, t

    pid, s, t = lattice(M)
    used = np.unique(pid)
    assert len(used) == 102, len(used)

    P = 2 * 34 * 36
    which = (rng.random(P) < 0.35).astype(np.int64)         # 35 % of planks come from the second source
    ox = rng.integers(2, sw - cw - 2, P).astype(np.float64)
    oy = rng.integers(2, sh - ch - 2, P).astype(np.float64)
    flip_s, flip_t = rng.random(P) < 0.5, rng.random(P) < 0.5
    # plank-to-plank tone +-6 %: each of the 6 rows of 17 planks gets the same stratified set of tones, shuffled;
    # of many shuffles keep the one with the least large-scale light/dark clumping (nothing to recognise when the tile repeats)
    rows = {}
    for p in used:
        rows.setdefault((p // (34 * 36), p % 36), []).append(p)
    assert len(rows) == 6 and all(len(r) == 17 for r in rows.values())
    lo, _, _ = lattice(144)
    levels = np.linspace(-0.06, 0.06, 17)
    best = None
    for _ in range(600):
        tone = np.ones(P)
        for r in rows.values():
            tone[r] = 1 + rng.permutation(levels)
        score = ndimage.gaussian_filter(tone[lo], 0.22 / TU * 144, mode='wrap').std()
        if best is None or score < best[0]:
            best = (score, tone)
    tone = best[1]
    warm = rng.uniform(-0.012, 0.012, P)                    # tiny warm/cool shift
    lum = S.mean(2)
    gain = np.ones(P)
    for p in used:                                          # normalise every crop so tone variation is exactly the +-6 % above
        y0, x0 = int(oy[p]) + which[p] * sh, int(ox[p])
        gain[p] = lum[:sh].mean() / lum[y0:y0 + ch, x0:x0 + cw].mean()
    ss = np.where(flip_s[pid], n - s, s)
    tt = np.where(flip_t[pid], 1 - t, t)
    sx = ox[pid] + ss * W * ppm
    sy = oy[pid] + tt * W * ppm + which[pid] * sh
    out = sample(S, sx, sy)
    g = (gain * tone)[pid]
    out *= np.dstack([g * (1 + warm[pid]), g, g * (1 - warm[pid])]).astype(np.float32)

    # hairline joints: darken within ~0.9 mm of every plank edge
    edge_mm = np.minimum(np.minimum(t, 1 - t), np.minimum(s, n - s)) * W * 1000
    jw = 1.0
    k = np.clip(1 - edge_mm / jw, 0, 1) ** 1.5
    out *= (1 - 0.66 * k)[..., None].astype(np.float32)

    im = T.to_im(out).reduce(SS)                            # box filter: exact area average, no ringing next to the joints
    im = exact_mean(im, 150)
    finish(im, 'parquet')
    return dict(file='assets/tex/parquet.webp', source='composed', model=MODEL,
                prompt=[PROMPTS['src_oak_parquet'] or '(unknown: raw/wood/src_oak_parquet-20261112-064114.png was left by an earlier interrupted run, prompt and model not recorded)',
                        PROMPTS['src_oak_veneer']],
                post='flatten both oak sources, grade to honey oak; herringbone composed in code at 3x supersampling: 102 planks 600x100 mm at 45 deg, '
                     'each plank its own crop (65 % src_oak_parquet, 35 % src_oak_veneer, random flips), crop means normalised then tone +-6 %, '
                     '(stratified per row of 17 planks, shuffle with least large-scale clumping), ~1 mm dark hairline joints; lattice-exact tile 17*(0.1*sqrt2) x 3*(0.6*sqrt2) m; 3x box downsample to 1024; set_mean 150',
                px=[N, N], tile_m=[round(TU, 4), round(TV, 4)])


# ------------------------------------------------------------------ walnut slats
def walnut_slats():
    Wp, Hp, SS = 512, 1024, 4
    TU, TV = 1.2, 2.4
    pitch, slat_w, n_slats = 0.05, 0.03, 24
    rng = np.random.default_rng(11)

    a = T.to_f(src('src_walnut'))                           # 1024 x 1536, grain vertical
    # remove any top-to-bottom lighting drift but keep the tone bands across the width (they give slat-to-slat variation)
    row = ndimage.gaussian_filter1d(a.mean((1, 2)), 120, mode='reflect')
    a = a * (row.mean() / row)[:, None, None]
    # make it periodic along the grain: cross-fade the top band over the bottom band
    h = a.shape[0]; b = int(h * 0.14)
    w = np.linspace(0, 1, b, dtype=np.float32)[:, None, None]
    a = np.concatenate([w * a[:b] + (1 - w) * a[h - b:], a[b:h - b]], 0)
    h, wsrc = a.shape[:2]                                   # h px of source = 2.4 m
    a = recolor(a, (158, 116, 88))                          # hue a touch less red; absolute level is set below

    strip = 22.0                                            # source px across one slat
    slots = rng.permutation(n_slats)                        # neighbouring slats come from far-apart columns
    x0 = 8 + slots * ((wsrc - 16 - strip) / (n_slats - 1)) + rng.uniform(-6, 6, n_slats)
    x0 = np.clip(x0, 2, wsrc - strip - 2)
    y0 = rng.uniform(0, h, n_slats)
    flip = rng.random(n_slats) < 0.5
    tone = 1 + rng.uniform(-0.08, 0.08, n_slats)
    lumc = ndimage.uniform_filter1d(a.mean((0, 2)), int(strip), mode='nearest')
    gain = lumc.mean() / lumc[(x0 + strip / 2).astype(int)]
    gain = 1 + (gain - 1) * 0.5                             # keep half of the natural band-to-band difference
    tone = tone * gain

    M, MH = Wp * SS, Hp * SS
    u = (np.arange(M) + 0.5) / M * TU
    vv = (np.arange(MH) + 0.5) / MH                         # 0..1 along the tile height
    k = np.floor(u / pitch).astype(int)
    loc = u - k * pitch
    gap = (pitch - slat_w) / 2                              # 10 mm of felt each side: the tile border is the middle of a gap
    t = (loc - gap) / slat_w
    on = (t >= 0) & (t <= 1)
    tc = np.clip(t, 0, 1)
    X = np.broadcast_to((x0[k] + np.where(flip[k], 1 - tc, tc) * strip)[None, :], (MH, M))
    Y = (y0[k][None, :] + vv[:, None] * h) % h
    wood = sample(a, X, Y, mode='grid-wrap')
    profile = 1 - 0.30 * np.abs(2 * tc - 1) ** 2.2          # rounded face: lighter centre, darker edges
    wood *= (profile * tone[k])[None, :, None].astype(np.float32)

    felt_rgb = np.array([43, 43, 45], np.float32) / 255
    noise = ndimage.gaussian_filter(rng.standard_normal((MH, M)).astype(np.float32), 1.5, mode='wrap')
    noise /= noise.std()
    felt = felt_rgb[None, None, :] * (1 + 0.10 * noise[..., None])
    # felt right next to a slat sits in its contact shadow
    dist = np.where(on, 0, np.minimum(np.abs(loc - gap), np.abs(loc - gap - slat_w)))
    felt = felt * (0.72 + 0.28 * np.clip(dist / 0.004, 0, 1))[None, :, None].astype(np.float32)

    # scale the wood so the whole tile (slats + felt) lands on the target mean
    target = 91.0
    frac = on.mean()
    need = (target / 255 - (1 - frac) * felt[:, ~on].mean()) / frac
    wood *= need / wood[:, on].mean()
    out = np.where(on[None, :, None], wood, felt)
    im = T.to_im(out).reduce(SS)                            # box filter: no ringing at the slat/felt edges
    im = exact_mean(im, target)
    back = np.asarray(finish(im, 'walnut_slats'), np.float32)
    cols = ((np.arange(Wp) + 0.5) / Wp * TU) % pitch
    face = back[:, (cols > gap + 0.003) & (cols < gap + slat_w - 0.003)].mean()
    felt_m = back[:, (cols < gap - 0.003) | (cols > gap + slat_w + 0.003)].mean()
    print('   slat faces mean %.1f, felt mean %.1f' % (face, felt_m))
    return dict(file='assets/tex/walnut_slats.webp', source='composed', model=MODEL, prompt=PROMPTS['src_walnut'],
                post='walnut veneer source: vertical drift removed, made periodic along the grain (top/bottom cross-fade), hue regraded slightly; '
                     '24 slats 30 mm + 20 mm black felt composed in code at 4x supersampling (felt gap centred on the tile border), each slat its own '
                     'column strip of the source with its own vertical offset, tone +-8 %%, rounded profile shading (centre 1.0, edges 0.70); 4x box downsample; '
                     'wood scaled so the mean of the WHOLE tile incl. the black felt is 91 (slat faces alone %.0f, felt %.0f)' % (face, felt_m),
                px=[Wp, Hp], tile_m=[TU, TV])


# ------------------------------------------------------------------ plain materials
def oak():
    # 1.2 m of the sheet's height; along the grain (u) a wider piece, because the border cross-fade there is much longer:
    # a short blend band across straight grain lines leaves a faint vertical zone of line ends at the tile border
    im = T.flatten(src('src_oak_veneer').crop((34, 0, 1502, 1024)), 0.14)
    im = tileable(im, band=0.14, seed=3, axes=(0,))        # across the grain: 1024 -> 881 px
    im = tileable(im, band=0.40, seed=3, axes=(1,))        # along the grain: 1468 -> 881 px, so the scale stays isotropic
    assert im.size == (881, 881), im.size
    im = resize_wrap(im, (512, 512))
    im = exact_mean(im, 165)
    finish(im, 'oak')
    return dict(file='assets/tex/oak.webp', source='generated', model=MODEL, prompt=PROMPTS['src_oak_veneer'],
                post='centre crop 1468x1024, flatten 0.14, contrast-preserving border cross-fade (14 % band across the grain, 40 % band along it -> 881x881), LANCZOS to 512, set_mean 165; grain along u',
                px=[512, 512], tile_m=[1.2, 1.2])


def bronze():
    rng = np.random.default_rng(5)
    a = T.to_f(tileable(T.flatten(src('src_bronze'), 0.08), band=0.14, seed=4, axes=(1,)))   # periodic across the brushing
    # along the brushing the streaks run the full height: a short cross-fade would show a line of streak ends, so fade the
    # top half into the bottom half over the whole height instead (the vertical stretch this implies is invisible on brushing)
    h = a.shape[0] // 2
    w = np.linspace(0, 1, h, dtype=np.float32)[:, None, None]; w = w * w * (3 - 2 * w)
    low = ndimage.gaussian_filter(a, (6, 6, 0), mode='reflect')
    a = w * low[:h] + (1 - w) * low[h:2 * h] + (w * (a[:h] - low[:h]) + (1 - w) * (a[h:2 * h] - low[h:2 * h])) / np.sqrt(w * w + (1 - w) * (1 - w))
    im = resize_wrap(T.to_im(a), (256, 256))
    a = T.to_f(im)
    # the hairline brushing of the source is finer than a texel at 256 px/m: re-add a faint, exactly periodic vertical brushing
    n1 = ndimage.gaussian_filter(rng.standard_normal((256, 256)).astype(np.float32), (40, 0.6), mode='wrap')
    n2 = ndimage.gaussian_filter(rng.standard_normal((256, 256)).astype(np.float32), (9, 0.45), mode='wrap')
    br = 0.022 * n1 / n1.std() + 0.012 * n2 / n2.std()
    a = a * (1 + br)[..., None]
    # WebP codes the top and the bottom block row independently, which left a faint line of streak ends at the top/bottom
    # border (decoded wrap difference 1.2 levels against 0.2 between neighbouring rows). Make the streaks exactly straight
    # for 8 px either side of that border (fading out over 16 px more): both block rows then code the same pattern.
    n = a.shape[0]; flat, fade = 8, 16
    dist = np.minimum(np.arange(n) + 0.5, n - np.arange(n) - 0.5)
    m = np.clip(1 - (dist - flat) / fade, 0, 1); m = (m * m * (3 - 2 * m))[:, None, None].astype(np.float32)
    ref = np.concatenate([a[n - flat - fade:], a[:flat + fade]], 0).mean(0, keepdims=True)
    a = a * (1 - m) + ref * m
    im = exact_mean(T.to_im(a), 60)
    finish(im, 'bronze', q=90)
    return dict(file='assets/tex/bronze.webp', source='generated', model=MODEL, prompt=PROMPTS['src_bronze'],
                post='flatten 0.08, contrast-preserving cross-fade (14 % band across the brushing, full-height fade along it), LANCZOS to 256, faint periodic vertical brushing noise added (about +-2.5 %), streaks straightened within 8-24 px of the top/bottom border (keeps the WebP wrap seam below the codec noise), set_mean 60',
                px=[256, 256], tile_m=[1.0, 1.0])


def leather():
    im = tileable(T.flatten(src('src_leather'), 0.07), band=0.14, seed=6)
    a = T.to_f(im)
    # the regrade below multiplies green and blue a lot, which turned a few slightly paler patches and specks of the source
    # into light marks that repeat with the tile: even out everything coarser than the pebble grain, per channel
    low = ndimage.gaussian_filter(a, (10, 10, 0), mode='wrap')
    a = a * (low.mean((0, 1)) / low)
    a = recolor(a, (123, 71, 45))                           # rust red-orange -> darker cognac brown
    im = resize_wrap(T.to_im(a), (512, 512))
    im = exact_mean(im, 80)
    finish(im, 'leather')
    return dict(file='assets/tex/leather.webp', source='generated', model=MODEL, prompt=PROMPTS['src_leather'],
                post='flatten 0.07, contrast-preserving border cross-fade 0.14, per-channel evening of everything coarser than the grain (gaussian sigma 10 px, wrap), per-channel regrade from rust to cognac brown, LANCZOS to 512, set_mean 80',
                px=[512, 512], tile_m=[1.0, 1.0])


BUILD = dict(parquet=parquet, walnut_slats=walnut_slats, oak=oak, bronze=bronze, leather=leather)

if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    names = sys.argv[1:] or list(BUILD)
    mpath = os.path.join(RAW, 'manifest.json')
    old = {e['file']: e for e in json.load(open(mpath))} if os.path.exists(mpath) else {}
    for nme in names:
        e = BUILD[nme]()
        e['mean_linear'] = T.mean_linear(Image.open(os.path.join(ROOT, e['file'])).convert('RGB'))
        old[e['file']] = e
    order = ['assets/tex/%s.webp' % k for k in BUILD]
    json.dump([old[f] for f in order if f in old], open(mpath, 'w'), indent=1, ensure_ascii=False)
